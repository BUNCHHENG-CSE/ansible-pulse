import json
from datetime import datetime, timezone
from typing import Dict, Any, List
from ..models.schemas import (
    ObservabilitySummary, AnsibleAsset, DuplicateCluster,
    RiskFlagItem, SecurityComplianceSummary
)

class ReportGenerator:
    """
    Enterprise Governance & Executive Audit Report Generator.
    Produces high-fidelity Markdown, standalone HTML (print/PDF-ready),
    and structured JSON reports for SRE Leads, Platform Directors, and CTOs.
    """

    @classmethod
    def generate_markdown(
        cls,
        summary: ObservabilitySummary,
        risks: List[RiskFlagItem],
        clusters: List[DuplicateCluster],
        security: SecurityComplianceSummary
    ) -> str:
        now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

        health_badge = "🟢 Excellent" if summary.overall_health_score >= 80 else ("🟡 Moderate Risk" if summary.overall_health_score >= 60 else "🔴 Critical Risk")
        sec_badge = f"Grade {security.grade} ({security.overall_score}/100)"

        md = f"""# TCT AnsiblePulse — Infrastructure Observability & Governance Audit Report

> **Generated on:** `{now_str}`  
> **Target Scope:** Multi-repository Ansible & IaC Infrastructure Estate  
> **Platform Status:** {health_badge} | Security: {sec_badge}  

---

## 1. Executive Summary & Fleet Health

| Metric Category | Value | Status Assessment |
| :--- | :---: | :--- |
| **Fleet Health Score** | **{summary.overall_health_score} / 100** | {health_badge} |
| **Security Compliance Score** | **{security.overall_score} / 100 ({security.grade})** | {security.total_findings} security finding(s) detected |
| **Repositories Scanned** | **{summary.total_repos_scanned}** | Dispersed enterprise multi-repo estate |
| **Discovered Playbooks** | **{summary.total_playbooks}** | Monitored execution targets |
| **Discovered Roles** | **{summary.total_roles}** | Shared & local modular roles |
| **Indexed Structured Tasks** | **{summary.total_tasks}** | Line-level parsed AST tasks |
| **Zombie Core Assets** | **{summary.zombie_core_assets_count}** | ⚠️ High-blast dependencies unmaintained >180 days |
| **Duplicate Task Clusters** | **{summary.duplicate_clusters_count}** | {summary.duplicate_tasks_count} divergent script variants |

---

## 2. Critical Governance Risks & Zombie Core Dependencies

Zombie core assets are foundational roles or playbooks that anchor multiple downstream production services but have sat abandoned without maintenance for over 6 months:

"""
        for r in risks[:10]:
            md += f"""### [{r.risk_level.value.upper()}] `{r.asset_name}` (`{r.repo_name}`)
- **Primary Flag:** {r.primary_risk_flag}
- **Downstream Blast Radius:** {r.blast_radius} dependent playbook(s) / microservice(s)
- **Staleness:** {r.staleness_days} days since last commit ({r.authors_count} historical author(s))
- **Execution Recency:** Last status `{r.last_execution_status.value.upper()}`
- **Suggested Action:** {r.suggested_action}

"""

        md += """---

## 3. Duplicate Sprawl & Parameter Divergence

Identical functional operations duplicated across multiple repositories with uncoordinated configuration drift:

| Functionality Group | Primary Module | Variants Count | Similarity | Recommended Canonical Version |
| :--- | :---: | :---: | :---: | :--- |
"""
        for c in clusters:
            md += f"| **{c.functionality_name}** | `{c.primary_module}` | {len(c.variants)} | {int(c.similarity_score * 100)}% | `{c.canonical_recommendation or 'N/A'}` |\n"

        md += f"""
---

## 4. Security & Compliance Findings

- **Total Security Findings:** {security.total_findings} (Critical: {security.critical_count}, High: {security.high_count}, Medium: {security.medium_count}, Low: {security.low_count})

"""
        for f in security.findings[:10]:
            md += f"- **[{f.severity.value.upper()}] {f.title}** (`{f.rule_id}` in `{f.repo_name}::{f.file_path}:{f.line_number}`)\n  - *Description:* {f.description}\n  - *Remediation:* {f.remediation_advice}\n\n"

        md += """---

## 5. Strategic 30-60-90 Day Remediation Roadmap

1. **Days 1–30 (Immediate Triage):**
   - Audit and assign active owners to flagged Zombie Core assets.
   - Resolve critical security findings (plaintext secrets, world-writable permissions).
2. **Days 31–60 (Role Consolidation):**
   - Deploy canonical consolidated roles generated by TCT AnsiblePulse for top duplicate clusters.
   - Replace divergent copy-pasted tasks with standard `include_role` invocations.
3. **Days 61–90 (CI/CD Governance Enforcement):**
   - Embed `cli.py gate` into pull request workflows to prevent new unapproved duplicate tasks or stale dependencies from entering main branches.

---
*Report produced automatically by TCT AnsiblePulse Read-Only Observability Engine.*
"""
        return md

